CENTER = (4138.6, 341.6)  # point of the text placed at the page centre (as draftwatermark does)


def watermark_ops(page):
    """PDF drawing commands that paint the watermark centred on this page."""
    box = page.cropbox
    cx = (box.left + box.right) / 2
    cy = (box.bottom + box.top) / 2
    # A page with /Rotate is turned when displayed; turn the text with it so it
    # still reads at ANGLE on screen.
    t = math.radians(ANGLE + page.rotation)
    a = SIZE / 1000 * math.cos(t)
    b = SIZE / 1000 * math.sin(t)
    # Scale + rotate, then shift so that CENTER lands on the page centre.
    e = cx - (a * CENTER[0] - b * CENTER[1])
    f = cy - (b * CENTER[0] + a * CENTER[1])
    return (f"q {GRAY} g {a:.6f} {b:.6f} {-b:.6f} {a:.6f} {e:.3f} {f:.3f} cm\n"
            f"{OUTLINE.strip()}\nf Q\n").encode()


def main():
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    src = Path(sys.argv[1])
    dst = Path(sys.argv[2]) if len(sys.argv) == 3 else src.with_name(src.stem + "_WP.pdf")

    writer = PdfWriter(clone_from=src)
    for page in writer.pages:
        old = page.get_contents()
        new = DecodedStreamObject()
        # Watermark first, so the page's own content is drawn on top of it.
        new.set_data(watermark_ops(page) + (old.get_data() if old is not None else b""))
        page.replace_contents(ContentStream(new, writer))
        page.compress_content_streams()
    writer.write(dst)
    print(f"wrote {dst} ({len(writer.pages)} pages)")


if __name__ == "__main__":
    main()
